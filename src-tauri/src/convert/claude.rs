//! Claude Code session files: `projects/<encoded cwd>/<sessionId>.jsonl`.
//!
//! Each line is an event; conversation lines have `type` user / assistant, a
//! `uuid` and `parentUuid` (a tree: rewinds create branches, compaction starts
//! a new root), `sessionId`, `cwd`, `timestamp` and `message` (Anthropic
//! Messages API shape: text / tool_use / tool_result / thinking blocks).

use std::collections::{HashMap, HashSet};
use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};

use serde_json::{json, Value};

use super::{clean_cwd, now_rfc3339, Conversation, Item, Out};
use crate::extract::sessions::for_each_json;
use crate::model::Tool;
use crate::paths::AgentPaths;

/// Version written into converted lines.
const WRITER_VERSION: &str = "2.1.0";
/// Model name on converted assistant messages.
pub const CONVERTED_MODEL: &str = "memdock-converted";

/// A "user" line Claude Code wrote itself, such as a background task
/// notification (`promptSource: "system"`, `origin.kind`).
fn is_system_prompt(v: &Value) -> bool {
    v.get("promptSource").and_then(Value::as_str) == Some("system")
        || v.pointer("/origin/kind").and_then(Value::as_str) == Some("task-notification")
}

fn is_noise_user(text: &str) -> bool {
    let t = text.trim_start();
    t.starts_with("[Request interrupted by user")
        || t.starts_with("<task-notification>")
        || t.starts_with("<local-command-caveat>")
        || t.starts_with("<command-")
        || t.starts_with("<local-command-")
        || t.starts_with("<system-reminder>")
        || t.starts_with("Caveat: The messages below were generated by the user while running local commands")
}

fn tool_result_text(content: &Value) -> String {
    match content {
        Value::String(s) => s.clone(),
        Value::Array(parts) => parts
            .iter()
            .map(|p| match p.get("type").and_then(Value::as_str) {
                Some("text") => p.get("text").and_then(Value::as_str).unwrap_or("").to_string(),
                Some("image") => "[image]".to_string(),
                _ => String::new(),
            })
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join("\n"),
        Value::Null => String::new(),
        other => other.to_string(),
    }
}

/// `data:` URI of an Anthropic image block with an inline base64 source.
fn image_data_uri(b: &Value) -> Option<String> {
    let src = b.get("source")?;
    if src.get("type").and_then(Value::as_str) != Some("base64") {
        return None;
    }
    let mt = src.get("media_type").and_then(Value::as_str).unwrap_or("image/png");
    let data = src.get("data").and_then(Value::as_str)?;
    Some(format!("data:{mt};base64,{data}"))
}

/// The uuids on the active branch: walk `parentUuid` back from the last
/// non-sidechain message. `None` when the file has no usable chain.
fn active_chain(path: &Path) -> Option<HashSet<String>> {
    let mut parents: HashMap<String, Option<String>> = HashMap::new();
    let mut leaf: Option<String> = None;
    for_each_json(path, |v| {
        let Some(uuid) = v.get("uuid").and_then(Value::as_str) else { return };
        let parent = v.get("parentUuid").and_then(Value::as_str).map(String::from);
        parents.insert(uuid.to_string(), parent);
        let kind = v.get("type").and_then(Value::as_str);
        let sidechain = v.get("isSidechain").and_then(Value::as_bool) == Some(true);
        if matches!(kind, Some("user") | Some("assistant")) && !sidechain {
            leaf = Some(uuid.to_string());
        }
    });
    let mut cur = leaf?;
    let mut chain = HashSet::new();
    loop {
        if !chain.insert(cur.clone()) {
            break; // cycle guard
        }
        match parents.get(&cur) {
            Some(Some(p)) if parents.contains_key(p) => cur = p.clone(),
            _ => break,
        }
    }
    Some(chain)
}

/// Parses a Claude Code session file (the active branch only; sidechains,
/// meta lines, thinking and synthetic API-error messages are dropped).
pub fn parse(path: &Path) -> Conversation {
    let stem = path.file_stem().map(|s| s.to_string_lossy().into_owned()).unwrap_or_default();
    let chain = active_chain(path);
    let mut conv = Conversation {
        tool: Tool::Claude,
        id: stem,
        cwd: String::new(),
        title: None,
        model: None,
        items: Vec::new(),
        images: Vec::new(),
    };
    let mut have_id = false;
    let mut last_ts = String::new();
    for_each_json(path, |v| {
        let kind = v.get("type").and_then(Value::as_str).unwrap_or("");
        match kind {
            "summary" => {
                if let Some(s) = v.get("summary").and_then(Value::as_str) {
                    conv.title.get_or_insert_with(|| s.to_string());
                }
                return;
            }
            "ai-title" => {
                if let Some(s) = v.get("aiTitle").and_then(Value::as_str) {
                    conv.title = Some(s.to_string());
                }
                return;
            }
            "custom-title" => {
                if let Some(s) = v.get("customTitle").and_then(Value::as_str) {
                    conv.title = Some(s.to_string());
                }
                return;
            }
            "user" | "assistant" => {}
            _ => return,
        }
        if v.get("isSidechain").and_then(Value::as_bool) == Some(true)
            || v.get("isMeta").and_then(Value::as_bool) == Some(true)
            || v.get("isApiErrorMessage").and_then(Value::as_bool) == Some(true)
            || is_system_prompt(&v)
        {
            return;
        }
        if let (Some(chain), Some(uuid)) = (&chain, v.get("uuid").and_then(Value::as_str)) {
            if !chain.contains(uuid) {
                return;
            }
        }
        if !have_id {
            if let Some(id) = v.get("sessionId").and_then(Value::as_str).filter(|s| !s.is_empty()) {
                conv.id = id.to_string();
                have_id = true;
            }
        }
        if conv.cwd.is_empty() {
            if let Some(c) = v.get("cwd").and_then(Value::as_str) {
                conv.cwd = clean_cwd(c);
            }
        }
        let ts = v
            .get("timestamp")
            .and_then(Value::as_str)
            .map(String::from)
            .unwrap_or_else(|| last_ts.clone());
        last_ts = ts.clone();
        let Some(msg) = v.get("message") else { return };
        if kind == "assistant" {
            if let Some(m) = msg.get("model").and_then(Value::as_str) {
                if m != CONVERTED_MODEL && !m.starts_with('<') {
                    conv.model = Some(m.to_string());
                }
            }
        }
        let content = msg.get("content").cloned().unwrap_or(Value::Null);
        let blocks: Vec<Value> = match content {
            Value::String(s) => vec![json!({"type": "text", "text": s})],
            Value::Array(a) => a,
            _ => return,
        };
        for b in blocks {
            match b.get("type").and_then(Value::as_str) {
                Some("text") => {
                    let text = b.get("text").and_then(Value::as_str).unwrap_or("");
                    if text.trim().is_empty() {
                        continue;
                    }
                    if kind == "user" {
                        if is_noise_user(text) {
                            continue;
                        }
                        conv.items.push(Item::User { ts: ts.clone(), text: text.to_string() });
                    } else {
                        conv.items.push(Item::Assistant { ts: ts.clone(), text: text.to_string() });
                    }
                }
                Some("image") if kind == "user" => {
                    conv.items.push(Item::User { ts: ts.clone(), text: "[image]".into() });
                    if let Some(uri) = image_data_uri(&b) {
                        conv.images.push((conv.items.len() - 1, uri));
                    }
                }
                Some("tool_use") => {
                    let name = b.get("name").and_then(Value::as_str).unwrap_or("tool").to_string();
                    let input = b.get("input").cloned().unwrap_or(Value::Null);
                    let shell = if name == "Bash" {
                        input.get("command").and_then(Value::as_str).map(String::from)
                    } else {
                        None
                    };
                    conv.items.push(Item::Call {
                        ts: ts.clone(),
                        id: b.get("id").and_then(Value::as_str).unwrap_or("").to_string(),
                        name,
                        input,
                        shell,
                    });
                }
                Some("tool_result") => {
                    conv.items.push(Item::Result {
                        ts: ts.clone(),
                        id: b.get("tool_use_id").and_then(Value::as_str).unwrap_or("").to_string(),
                        output: tool_result_text(b.get("content").unwrap_or(&Value::Null)),
                        is_error: b.get("is_error").and_then(Value::as_bool) == Some(true),
                    });
                }
                // thinking / redacted_thinking and unknown blocks are dropped.
                _ => {}
            }
        }
    });
    conv
}

/// Claude Code's project directory name for `cwd`: every non-alphanumeric
/// character becomes `-`.
pub fn encode_project_dir(cwd: &str) -> String {
    cwd.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '-' }).collect()
}

/// Directory for sessions of `cwd`: an existing project directory whose
/// sessions record that cwd wins, else the encoded name.
pub fn project_dir(paths: &AgentPaths, cwd: &str) -> PathBuf {
    let id = crate::projects::normalize_path(cwd);
    if let Some(dir) = crate::projects::claude_project_dirs(paths).remove(&id) {
        return dir;
    }
    paths.claude_home.join("projects").join(encode_project_dir(cwd))
}

struct LineWriter {
    lines: Vec<String>,
    session_id: String,
    cwd: String,
    parent: Option<String>,
}

impl LineWriter {
    fn base(&mut self, kind: &str, ts: &str) -> (String, serde_json::Map<String, Value>) {
        let uuid = uuid::Uuid::new_v4().to_string();
        let mut m = serde_json::Map::new();
        m.insert("parentUuid".into(), self.parent.clone().map(Value::String).unwrap_or(Value::Null));
        m.insert("isSidechain".into(), Value::Bool(false));
        m.insert("userType".into(), json!("external"));
        m.insert("cwd".into(), json!(self.cwd));
        m.insert("sessionId".into(), json!(self.session_id));
        m.insert("version".into(), json!(WRITER_VERSION));
        m.insert("gitBranch".into(), json!(""));
        m.insert("type".into(), json!(kind));
        m.insert("uuid".into(), json!(uuid));
        m.insert("timestamp".into(), json!(ts));
        (uuid, m)
    }

    fn push(&mut self, uuid: String, m: serde_json::Map<String, Value>) {
        self.lines.push(Value::Object(m).to_string());
        self.parent = Some(uuid);
    }

    fn user(&mut self, ts: &str, content: Value, extra: Option<(&str, Value)>) {
        let (uuid, mut m) = self.base("user", ts);
        m.insert("message".into(), json!({"role": "user", "content": content}));
        if let Some((k, v)) = extra {
            m.insert(k.into(), v);
        }
        self.push(uuid, m);
    }

    fn assistant(&mut self, ts: &str, content: Value, stop: &str) -> String {
        let (uuid, mut m) = self.base("assistant", ts);
        m.insert(
            "message".into(),
            json!({
                "id": format!("msg_memdock_{}", uuid::Uuid::new_v4().simple()),
                "type": "message",
                "role": "assistant",
                "model": CONVERTED_MODEL,
                "content": content,
                "stop_reason": stop,
                "stop_sequence": null,
                "usage": {"input_tokens": 0, "output_tokens": 0, "cache_creation_input_tokens": 0, "cache_read_input_tokens": 0}
            }),
        );
        self.push(uuid.clone(), m);
        uuid
    }
}

/// Renders planned output as Claude Code jsonl lines. The first message is
/// always a user message; every tool_use is immediately followed by its
/// tool_result.
pub fn render(out: &[Out], session_id: &str, cwd: &str, note: Option<&str>) -> Vec<String> {
    let mut w = LineWriter {
        lines: Vec::new(),
        session_id: session_id.to_string(),
        cwd: cwd.to_string(),
        parent: None,
    };
    let first_ts = out
        .first()
        .map(|o| match o {
            Out::User { ts, .. } | Out::Assistant { ts, .. } | Out::Shell { ts, .. } => ts.clone(),
        })
        .unwrap_or_else(now_rfc3339);
    if !matches!(out.first(), Some(Out::User { .. })) {
        w.user(&first_ts, json!("(Continuing a conversation converted by MemDock.)"), None);
    }
    for o in out {
        match o {
            Out::User { ts, text } => w.user(ts, json!(text), None),
            Out::Assistant { ts, text } => {
                w.assistant(ts, json!([{"type": "text", "text": text}]), "end_turn");
            }
            Out::Shell { ts, result_ts, command, output, is_error } => {
                let tool_id = format!("toolu_memdock_{}", uuid::Uuid::new_v4().simple());
                let a = w.assistant(
                    ts,
                    json!([{
                        "type": "tool_use",
                        "id": tool_id,
                        "name": "Bash",
                        "input": {"command": command, "description": "Converted shell command"}
                    }]),
                    "tool_use",
                );
                let (stdout, stderr) = if *is_error { (String::new(), output.clone()) } else { (output.clone(), String::new()) };
                let (uuid, mut m) = w.base("user", result_ts);
                m.insert(
                    "message".into(),
                    json!({"role": "user", "content": [{
                        "type": "tool_result",
                        "tool_use_id": tool_id,
                        "content": output,
                        "is_error": is_error
                    }]}),
                );
                m.insert(
                    "toolUseResult".into(),
                    json!({"stdout": stdout, "stderr": stderr, "interrupted": false, "isImage": false}),
                );
                m.insert("sourceToolAssistantUUID".into(), json!(a));
                w.push(uuid, m);
            }
        }
    }
    if let Some(n) = note {
        let ts = now_rfc3339();
        w.assistant(&ts, json!([{"type": "text", "text": n}]), "end_turn");
    }
    w.lines
}

/// Writes `lines` to `dir/<session_id>.jsonl` (never overwrites).
pub fn write(dir: &Path, session_id: &str, lines: &[String]) -> std::io::Result<PathBuf> {
    fs::create_dir_all(dir)?;
    let path = dir.join(format!("{session_id}.jsonl"));
    let mut f = fs::OpenOptions::new().write(true).create_new(true).open(&path)?;
    let mut body = lines.join("\n");
    body.push('\n');
    if let Err(e) = f.write_all(body.as_bytes()).and_then(|_| f.sync_all()) {
        drop(f);
        let _ = fs::remove_file(&path);
        return Err(e);
    }
    Ok(path)
}
